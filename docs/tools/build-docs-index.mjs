// Generates, from the HTML pages of the docs:
//   docs/assets/search-index.js  the search index, one entry per section (h2 or h3), text and code included
//   docs/llms.txt, docs/llms-full.txt, docs/llms-small.txt  the docs for LLMs (see docs/tools/llms.mjs)
// Usage: npm run docs:index         (regenerates the files)
//        npm run docs:check         (fails if a file is out of date; npm run check regenerates them)
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { buildLlmsFiles, readNav } from './llms.mjs';

const DOCS = new URL('../', import.meta.url).pathname;

/** Same rule as docs/assets/site.js: the anchors must match. */
function slugify(text) {
  return text
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

const decode = (text) =>
  text
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, '&');

// The code is extracted before stripping the tags: otherwise its generics (`<{ … }>`) would be taken for HTML.
function toText(html) {
  const code = [];
  const prose = html.replace(/<script type="text\/x-code"[^>]*>([\s\S]*?)<\/script>/g, (_, source) => {
    code.push(source);
    return ` \u0000${code.length - 1}\u0000 `;
  });
  return decode(prose.replace(/<[^>]+>/g, ' '))
    .replace(/\u0000(\d+)\u0000/g, (_, i) => code[Number(i)])
    .replace(/\s+/g, ' ')
    .trim();
}

const entries = [];
for (const file of readdirSync(DOCS).filter((name) => name.endsWith('.html')).sort()) {
  const html = readFileSync(join(DOCS, file), 'utf8');
  const article = html.match(/<article[^>]*>([\s\S]*?)<\/article>/)?.[1] ?? '';
  const page = toText(article.match(/<h1[^>]*>([\s\S]*?)<\/h1>/)?.[1] ?? file);

  // Splits the article into sections: the intro (before the first h2), then each h2 / h3.
  const parts = article.split(/(?=<h[23][\s>])/);
  for (const part of parts) {
    const heading = part.match(/^<h([23])([^>]*)>([\s\S]*?)<\/h\1>/);
    const title = heading ? toText(heading[3]) : page;
    const id = heading ? (heading[2].match(/id="([^"]+)"/)?.[1] ?? slugify(title)) : '';
    const body = toText(heading ? part.slice(heading[0].length) : part.replace(/<h1[^>]*>[\s\S]*?<\/h1>/, ''));
    if (!body && !heading) continue;
    entries.push({ url: id ? `${file}#${id}` : file, page, title, text: body });
  }
}

// Every link to the examples app (data-source of an excerpt, or href="../examples/…") must target a file that exists.
const ROOT = join(DOCS, '..');
const broken = [];
for (const file of readdirSync(DOCS).filter((name) => name.endsWith('.html'))) {
  const html = readFileSync(join(DOCS, file), 'utf8');
  const sources = [...html.matchAll(/data-source="([^"]+)"/g), ...html.matchAll(/href="\.\.\/(examples\/[^"#]+)"/g)].map((m) => m[1]);
  for (const source of sources) {
    if (!existsSync(join(ROOT, source))) broken.push(`${file} -> ${source}`);
  }
}
if (broken.length > 0) {
  console.error(`Broken links to the examples app:\n${broken.join('\n')}`);
  process.exit(1);
}

// Every page must be in the table of contents: it orders the navigation and the files for LLMs.
const listed = new Set(readNav(DOCS).flatMap((group) => group.items.map(([file]) => file)));
const unlisted = readdirSync(DOCS).filter((name) => name.endsWith('.html') && !listed.has(name));
if (unlisted.length > 0) {
  console.error(`Pages missing from the table of contents (NAV in docs/assets/site.js):\n${unlisted.join('\n')}`);
  process.exit(1);
}

const outputs = {
  'assets/search-index.js': `// Generated by docs/tools/build-docs-index.mjs: do not edit by hand.\nwindow.SEARCH_INDEX = ${JSON.stringify(entries)};\n`,
  ...buildLlmsFiles(DOCS),
};

if (process.argv.includes('--check')) {
  const stale = Object.entries(outputs)
    .filter(([file, content]) => !existsSync(join(DOCS, file)) || readFileSync(join(DOCS, file), 'utf8') !== content)
    .map(([file]) => `docs/${file}`);
  if (stale.length > 0) {
    console.error(`Generated docs files out of date: ${stale.join(', ')}. Run \`npm run docs:index\`.`);
    process.exit(1);
  }
  console.log(`Search index (${entries.length} sections) and LLM files up to date.`);
} else {
  for (const [file, content] of Object.entries(outputs)) writeFileSync(join(DOCS, file), content);
  console.log(`${entries.length} sections indexed in docs/assets/search-index.js`);
  console.log('LLM files written: docs/llms.txt, docs/llms-full.txt, docs/llms-small.txt');
}
