/**
 * Name → contract class dictionary, for the compiler. Filled by the file generated by the Vite
 * plugin (`src/@core/contracts.d.ts`): you never write it by hand.
 */
// biome-ignore lint/suspicious/noEmptyInterface: completed by module augmentation
export interface Contracts {}

/** The name of a contract known to the app: `'cart'`. */
export type ContractName = keyof Contracts & string;

/* ------------------------------------------------------------------------------------------ */
/* SuperContract                                                                               */
/* ------------------------------------------------------------------------------------------ */

declare const TYPES: unique symbol;
declare const CONTRACT: unique symbol;

/** What a contract declares: its state, its commands, its events. */
export type ContractTypes = { state: object; commands?: CommandMap; events?: Events };

/**
 * A store contract: its name, its types (`state`, `commands`, `events`), and its selectors,
 * written as methods that receive the state as their first parameter.
 *
 * ```ts
 * export class CartContract extends SuperContract<CartTypes> {
 *   constructor() {
 *     super({ name: 'cart' });
 *   }
 *   count(s: CartState) {
 *     return Object.values(s.quantities).reduce((sum, n) => sum + n, 0);
 *   }
 * }
 * ```
 */
export abstract class SuperContract<T extends ContractTypes> {
  /** Phantom: only exists for the compiler. */
  declare readonly [TYPES]?: T;
  readonly name: string;

  constructor(options: { name: string } & KnownKeys<T>) {
    this.name = options.name;
  }
}

/**
 * Rejects an unknown key in the types of a contract (`command` instead of `commands`): the error
 * shows on `super({ name })`, with the offending key and the expected keys.
 */
type KnownKeys<T> = [Exclude<keyof T, keyof ContractTypes>] extends [never]
  ? {}
  : {
      [K in Exclude<keyof T, keyof ContractTypes> &
        string as `unknown key in the contract types: ${K} (expected: state, commands, events)`]: never;
    };

type AnyContract = SuperContract<any>;
type TypesOf<K> = K extends SuperContract<infer T> ? T : never;

/** The state declared by a class contract. */
export type ContractState<K> = TypesOf<K>['state'];
/** The commands declared by a class contract. */
export type ContractCommands<K> = TypesOf<K> extends { commands: infer C extends CommandMap } ? C : {};
/** The events declared by a class contract. */
export type ContractEvents<K> = TypesOf<K> extends { events: infer E extends Events } ? E : {};

type SelectorKey<K> = {
  [M in keyof K]-?: M extends 'name' | 'constructor' ? never : K[M] extends (state: any, ...args: any[]) => any ? M : never;
}[keyof K];

/** The selectors of a class contract, with the state as first parameter. */
export type ContractSelectors<K> = { [M in SelectorKey<K>]: K[M] };

/** A selector whose first parameter does not accept the contract state. */
type MisplacedState<K> = {
  [M in SelectorKey<K>]: K[M] extends (...args: infer A) => any
    ? A extends []
      ? never // no parameter: it ignores the state, nothing to check
      : [ContractState<K>] extends [A[0]]
        ? never
        : M
    : never;
}[SelectorKey<K>];

/**
 * Checks the selectors of a contract, at the declaration of its store (`SuperStore<CartContract>`):
 * - their first parameter accepts the contract state (it is annotated by hand);
 * - none is called `pending`, which Super provides along with the selectors.
 */
export type CheckedContract<K> = {
  [M in MisplacedState<K>]: {
    error: 'the first parameter of a selector is the contract state';
    expected: (state: ContractState<K>, ...args: any[]) => unknown;
  };
} & ('pending' extends SelectorKey<K> ? { pending: { error: '"pending" is reserved: Super provides it along with the selectors' } } : {});

/** The selectors of a class contract, with the state already supplied, plus `pending(…)`. */
export type BoundContractSelectors<K> = BoundSelectors<ContractSelectors<K>> & PendingReader<ContractCommands<K>>;

/** The handle of a store that implements this class contract: what `CartStore.create()` returns. */
export type ContractStore<K> = StoreHandle<ContractState<K>, ContractCommands<K>, ContractEvents<K>, ContractSelectors<K>>;

/** The handle of a store, by the name of its contract: `StoreOfContract<'cart'>`, to type a dependency. */
export type StoreOfContract<N extends ContractName> = ContractStore<Contracts[N]>;

type ContractClass = abstract new () => AnyContract;

/** Under the hood: name → class, filled by the Vite plugin's virtual module. */
const registry = new Map<string, () => ContractClass>();
const compiled = new WeakMap<ContractClass, Contract<any, any, any, any>>();

/** Internal: registers a class contract under its name (done by the Vite plugin, or by a framework test). */
export function registerContract(name: string, load: () => ContractClass): void {
  registry.set(name, load);
}

/** Internal: the class registered under this name. */
export function contractClass(name: string): ContractClass {
  const load = registry.get(name);
  if (!load) {
    throw new Error(`[super] no contract named "${name}". Contracts are read from src/@core/*.contract.ts by the Super Vite plugin.`);
  }
  return load();
}

/**
 * Internal: the contract as read by the runtime, built once per class. The selectors are the
 * methods of the class (and of its parents up to `SuperContract`).
 */
export function compileContract(Class: ContractClass): Contract<any, any, any, any> {
  const cached = compiled.get(Class);
  if (cached) return cached;
  const instance = new (Class as unknown as new () => AnyContract)();
  const selectors: Record<string, (state: object, ...args: unknown[]) => unknown> = {};
  for (let proto = Object.getPrototypeOf(instance); proto && proto !== SuperContract.prototype; proto = Object.getPrototypeOf(proto)) {
    for (const key of Object.getOwnPropertyNames(proto)) {
      if (key === 'constructor' || key in selectors) continue;
      const method = Object.getOwnPropertyDescriptor(proto, key)?.value;
      if (typeof method !== 'function') continue;
      if (key === 'pending') throw new Error('[super] "pending" is reserved: Super provides it along with the selectors');
      selectors[key] = (state, ...args) => method.call(instance, state, ...args);
    }
  }
  const contract = Object.freeze({ name: instance.name, __selectors: Object.freeze(selectors) });
  compiled.set(Class, contract);
  return contract;
}

/** Internal: the contract as read by the runtime, by its name. */
export const contractByName = (name: string) => compileContract(contractClass(name));

