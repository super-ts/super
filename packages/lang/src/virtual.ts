/**
 * Virtual TypeScript of a `.super` file: the TS of the file copied verbatim, each element replaced
 * by flat typed calls (see `check.ts`), and a position mapping table
 * to report compiler errors in the `.super` file.
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  type Attribute,
  type ChildNode,
  type ClassInfo,
  type ElementNode,
  parse,
  type Span,
  type SuperFile,
  type SuperMember,
} from './parser.ts';

/**
 * A range of the virtual TS and the range of the source it comes from. `verify: false`: useful to
 * the editor (completion, hover) but its errors are not reported (incomplete code).
 */
export type Mapping = { source: Span; generated: Span; verify?: false; complete?: false };

export type VirtualCode = {
  code: string;
  mappings: Mapping[];
  file: SuperFile;
};

/**
 * The declarations of `check.ts`, appended to the virtual TS in a `declare namespace __s`:
 * the virtual TS imports nothing, it is checked with the project's tsconfig as is (CLI and IDE alike).
 */
const CHECK_NAMESPACE = `\ndeclare namespace __s {\n${readFileSync(join(import.meta.dirname, 'check.ts'), 'utf8')
  .replace(/^\/\*\*[\s\S]*?\*\/\n/, '')
  .replaceAll('export declare function', 'export function')
  .replaceAll('export declare const', 'export const')}}\n`;

/**
 * `assist`: for the editor only, incomplete statements (`if (this.` being typed)
 * keep their expression, for completion. That TS may be invalid: `super-tsc` and the
 * files written to disk do without it (a syntax error would stop `tsc` from type checking
 * the whole project).
 */
export function toVirtual(source: string, { assist = false } = {}): VirtualCode {
  const file = parse(source);
  const out = new Writer(source);
  // A method that emits elements returns what it emits (`Children`): it is written before its `}`,
  // so that `{this.#row(item)}` or `footer={this.#footer()}` have the right type.
  const emitting = file.methods.filter((m) =>
    file.parts.some((p) => p.kind === 'element' && m.start < p.span.start && p.span.end <= m.end),
  );
  const edits: Edit[] = [
    ...emitting.map((m) => ({ start: m.end, end: m.end, write: (w: Writer) => w.raw(' return __s.CHILDREN; ') })),
    ...file.classes.flatMap((info) => classEdits(source, info)),
  ].sort((a, b) => a.start - b.start || a.end - b.end);
  for (const part of file.parts) {
    if (part.kind !== 'code') {
      new ElementWriter(out, assist).element(part);
      continue;
    }
    let at = part.span.start;
    for (const edit of edits.filter((e) => e.start >= part.span.start && e.start < part.span.end)) {
      out.copy({ start: at, end: edit.start });
      edit.write(out);
      at = edit.end;
    }
    out.copy({ start: at, end: part.span.end });
  }
  out.raw(CHECK_NAMESPACE);
  return { code: out.code, mappings: out.mappings, file };
}

/** A replaced piece of the source (or an insertion, `start === end`) in the virtual TS. */
type Edit = Span & { write(out: Writer): void };

const STATIC_TAG = /\bstatic\s+tag\s*=\s*(['"])([^'"]+)\1/;

/**
 * What the virtual TS writes for a component:
 * - its types, after `SuperElement`: `SuperElement<{ route: __s.RouteOfTag<'counter-screen'> } &
 *   { props: { id: string }; emits: { … } }>`. The tag → route link is generated by the Vite plugin
 *   from `.screens(…)`; a component that is not a screen sees all routes;
 * - its declarations: `@tag` becomes `static tag`, `@prop name: T` a read-only property
 *   (`this.name`), `@title` an assignment to `this.page.title`, `@emit` disappears (it is in the types).
 */
function classEdits(source: string, info: ClassInfo): Edit[] {
  if (!info.element) return [];
  const edits: Edit[] = [];
  const tagMember = info.members.find((m): m is Extract<SuperMember, { kind: 'tag' | 'title' }> => m.kind === 'tag');
  const tag = tagMember
    ? /^(['"])([^'"]+)\1$/.exec(source.slice(tagMember.value.start, tagMember.value.end))?.[2]
    : STATIC_TAG.exec(source.slice(info.body.start, info.body.end))?.[2];
  const route = tag ? `{ route: __s.RouteOfTag<'${tag}'> }` : null;
  const props = info.members.filter((m) => m.kind === 'prop');
  const emits = info.members.filter((m) => m.kind === 'emit');
  const { generic, end } = info.element;
  if (generic) {
    if (route) edits.push({ start: generic.start + 1, end: generic.start + 1, write: (out) => out.raw(`${route} & `) });
  } else if (route || props.length > 0 || emits.length > 0) {
    edits.push({
      start: end,
      end,
      write: (out) => {
        out.raw('<');
        if (route) out.raw(route);
        if (props.length > 0 || emits.length > 0) {
          if (route) out.raw(' & ');
          out.raw('{ ');
          if (props.length > 0) {
            out.raw('props: { ');
            for (const p of props) {
              out.copy(p.name);
              out.raw(p.optional || p.init ? '?: ' : ': ');
              out.copy(p.type);
              out.raw('; ');
            }
            out.raw('}; ');
          }
          if (emits.length > 0) {
            out.raw('emits: { ');
            for (const e of emits) {
              out.copy(e.name);
              out.raw(': ');
              out.copy(e.type);
              out.raw('; ');
            }
            out.raw('}; ');
          }
          out.raw('}');
        }
        out.raw('>');
      },
    });
  }
  const named = props;
  for (const m of info.members) {
    edits.push({
      ...m.span,
      write: (out) => {
        switch (m.kind) {
          case 'tag':
            out.raw('static tag = ');
            out.copy(m.value);
            out.raw(';');
            return;
          case 'title':
            out.raw('protected readonly __superTitle = (this.page.title = (');
            out.copy(m.value);
            out.raw('));');
            return;
          case 'prop':
            out.raw(m.init ? 'readonly ' : 'declare readonly ');
            out.copy(m.name);
            out.raw(m.optional ? '?: ' : ': ');
            out.copy(m.type);
            if (m.init) {
              out.raw(' = (');
              out.copy(m.init);
              out.raw(')');
            }
            out.raw(';');
            // Once per class, with the first prop: the names must not be those of an HTML element.
            if (m === named[0]) {
              // In a method (never called): a field or a static block would read `__s` before its declaration.
              out.raw(' protected __superNames() { ');
              for (const p of named) {
                out.raw('__s.ownName(');
                out.quoted(p.name);
                out.raw('); ');
              }
              out.raw('}');
            }
            return;
          case 'emit':
            return;
          case 'contract':
            out.raw('readonly ');
            out.copy(m.name);
            out.raw(' = this.contract(');
            if (m.value) out.copy(m.value);
            else out.map(m.name, () => out.raw(`'${source.slice(m.name.start, m.name.end).replace('#', '')}'`));
            out.raw(');');
            return;
          case 'selector':
          case 'state':
          case 'form':
            out.raw('readonly ');
            out.copy(m.name);
            out.raw(` = this.${m.kind}(`);
            out.copy(m.value);
            out.raw(');');
            return;
          case 'ref':
            out.raw('readonly ');
            out.copy(m.name);
            out.raw(' = this.ref<');
            out.copy(m.type);
            out.raw('>();');
            return;
          case 'on': {
            // The method becomes the function passed to `on`: its parameters are typed by the event.
            out.raw('protected readonly ');
            out.copy(m.name);
            out.raw(' = ');
            if (source.slice(m.contract.start + 1, m.contract.end - 1) === 'router') out.map(m.contract, () => out.raw('this.router'));
            else {
              out.raw('this.contract(');
              out.copy(m.contract);
              out.raw(')');
            }
            out.raw('.on(');
            out.copy(m.event);
            out.raw(m.async ? ', async ' : ', ');
            out.copy(m.head);
            out.raw(' => ');
            out.copy(m.body);
            out.raw(');');
            return;
          }
        }
      },
    });
  }
  return edits;
}

/**
 * The content of a component: its direct children (without whitespace or comments), and its
 * named slots `<:name>`.
 */
export function contentOf(source: string, node: ElementNode): { children: ChildNode[]; slots: ElementNode[] } {
  const children: ChildNode[] = [];
  const slots: ElementNode[] = [];
  for (const child of node.children ?? []) {
    if (child.kind === 'element' && child.slot !== undefined) slots.push(child);
    else if (child.kind === 'comment' || (child.kind === 'text' && source.slice(child.span.start, child.span.end).trim() === '')) continue;
    else children.push(child);
  }
  return { children, slots };
}

/** Position in the source of a position in the virtual TS (the narrowest range that contains it). */
export function toSource(virtual: VirtualCode, offset: number): Span | null {
  let best: Mapping | null = null;
  for (const m of virtual.mappings) {
    if (offset < m.generated.start || offset > m.generated.end) continue;
    if (!best || m.generated.end - m.generated.start < best.generated.end - best.generated.start) best = m;
  }
  if (!best) return null;
  const { source, generated } = best;
  // Ranges of the same length: character by character mapping.
  if (source.end - source.start === generated.end - generated.start) {
    const at = source.start + (offset - generated.start);
    return { start: at, end: at };
  }
  return source;
}

class Writer {
  code = '';
  mappings: Mapping[] = [];
  readonly src: string;

  constructor(src: string) {
    this.src = src;
  }

  raw(text: string) {
    this.code += text;
  }

  /** Copies a range of the source, with its mapping. */
  copy(span: Span, verify = true) {
    this.map(span, () => this.raw(this.src.slice(span.start, span.end)));
    if (!verify) this.mappings[this.mappings.length - 1] = { ...(this.mappings.at(-1) as Mapping), verify: false };
  }

  /** A tag or attribute name: completion there comes from the tag service, not from TS. */
  name(span: Span) {
    this.copy(span);
    this.mappings[this.mappings.length - 1] = { ...(this.mappings.at(-1) as Mapping), complete: false };
  }

  /** `'name'`: the whole string (quotes included) maps to the name, to attach the error to it. */
  quoted(span: Span) {
    this.map(span, () => {
      this.raw("'");
      this.name(span);
      this.raw("'");
    });
  }

  /** Maps everything `write` writes to the `source` range. */
  map(source: Span, write: () => void) {
    const start = this.code.length;
    write();
    this.mappings.push({ source, generated: { start, end: this.code.length } });
  }
}

class ElementWriter {
  #next = 0;
  readonly out: Writer;
  readonly assist: boolean;

  constructor(out: Writer, assist: boolean) {
    this.out = out;
    this.assist = assist;
  }

  element(node: ElementNode) {
    if (node.component) this.out.map(node.span, () => this.component(node));
    else this.intrinsic(node);
  }

  intrinsic(node: ElementNode) {
    const { out } = this;
    // A variable only if an attribute uses it (no unused variable).
    const el = node.attributes.length > 0 ? `__e${this.#next++}` : null;
    // The opening tag only: the children have their own mappings (a range covering
    // the whole element would also attach to it the errors of a child's incomplete code).
    out.map(node.openSpan, () => {
      out.raw(el ? `{ const ${el} = __s.open(` : `{ __s.open(`);
      out.quoted(node.nameSpan);
      out.raw('); ');
      if (el) for (const attribute of node.attributes) this.attribute(el, attribute);
    });
    for (const child of node.children ?? []) this.child(child);
    out.raw('}');
  }

  attribute(el: string, attribute: Attribute) {
    const { out } = this;
    if (attribute.kind === 'directive') {
      out.map(attribute.span, () => {
        out.raw(`__s.use(${el}, `);
        out.copy(attribute.expr);
        out.raw('); ');
      });
      return;
    }
    const { name, nameSpan, value } = attribute;
    if (name === 'ref' && value?.kind === 'expr') {
      out.map(attribute.span, () => {
        out.raw(`__s.use(${el}, `);
        out.copy(value.span);
        out.raw('); ');
      });
      return;
    }
    const [fn, bare] = name.startsWith('on:') ? ['on', name.slice(3)] : name.startsWith('prop:') ? ['prop', name.slice(5)] : ['attr', name];
    const bareSpan = { start: nameSpan.end - bare.length, end: nameSpan.end };
    out.map(attribute.span, () => {
      out.raw(`__s.${fn}(${el}, `);
      out.quoted(bareSpan);
      out.raw(', ');
      if (value === null) out.raw('true');
      else out.copy(value.span);
      out.raw('); ');
    });
  }

  component(node: ElementNode) {
    const { out } = this;
    const props = node.attributes.filter((a) => a.kind === 'attr' && !a.name.startsWith('on:'));
    const events = node.attributes.filter((a) => a.kind === 'attr' && a.name.startsWith('on:'));
    const { children, slots } = contentOf(out.src, node);
    out.raw('{ ');
    // The children and slots first, flat (type narrowing applies there),
    // then the `create` call that receives the `content` prop and the `name` prop of each slot.
    for (const child of children) this.child(child);
    for (const slot of slots) for (const child of slot.children ?? []) this.child(child);
    out.name(node.nameSpan);
    out.raw('.create(');
    if (props.length > 0 || events.length > 0 || children.length > 0 || slots.length > 0) {
      out.map(node.openSpan, () => {
        out.raw('{ ');
        for (const a of props) this.property(a, a.kind === 'attr' ? a.nameSpan : a.span);
        // Attached to the children (or to the slot name): "children does not exist in Props"
        // is reported there.
        const first = children[0];
        if (first)
          out.map({ start: first.span.start, end: (children.at(-1) as ChildNode).span.end }, () => out.raw('content: __s.CHILDREN, '));
        for (const slot of slots) {
          out.name({ start: slot.nameSpan.start + 1, end: slot.nameSpan.end });
          out.raw(': __s.CHILDREN, ');
        }
        out.raw('}');
      });
    }
    if (events.length > 0) {
      out.raw(', { on: { ');
      for (const a of events) {
        if (a.kind !== 'attr') continue;
        this.property(a, { start: a.nameSpan.start + 3, end: a.nameSpan.end });
      }
      out.raw('} }');
    }
    out.raw('); }');
  }

  /** `name: value, ` in the props or listeners object of a component. */
  property(attribute: Attribute, keySpan: Span) {
    if (attribute.kind !== 'attr') return;
    const { out } = this;
    // A bare key if it is an identifier: TS messages quote it as is.
    const quote = /^[A-Za-z_$][\w$]*$/.test(out.src.slice(keySpan.start, keySpan.end)) ? '' : "'";
    out.map(attribute.span, () => {
      out.raw(quote);
      out.name(keySpan);
      out.raw(`${quote}: `);
      if (attribute.value === null) out.raw('true');
      else out.copy(attribute.value.span);
      out.raw(', ');
    });
  }

  child(node: ChildNode) {
    const { out } = this;
    switch (node.kind) {
      case 'text':
      case 'comment':
        return;
      case 'partial':
        // For completion only: the incomplete statement is already reported by the parser.
        if (!this.assist) return;
        out.map(node.span, () => {
          out.raw(`${node.keyword} (`);
          out.copy(node.expr, false);
          out.raw(') {');
          if (node.key) {
            out.raw(' __s.key(');
            out.copy(node.key, false);
            out.raw('); ');
          }
          out.raw('}');
        });
        out.mappings[out.mappings.length - 1] = { ...(out.mappings.at(-1) as Mapping), verify: false };
        out.raw(' ');
        return;
      case 'expr':
        out.map(node.span, () => {
          out.raw('__s.text(');
          out.copy(node.expr);
          out.raw('); ');
        });
        return;
      case 'element':
        // A slot outside a component (already reported): its children only.
        if (node.slot !== undefined) for (const child of node.children ?? []) this.child(child);
        else this.element(node);
        out.raw(' ');
        return;
      case 'declaration':
        out.copy(node.span);
        // `;` added if the source left it out (declaration being typed, already reported).
        out.raw(out.src[node.span.end - 1] === ';' ? ' ' : '; ');
        return;
      case 'if':
        node.branches.forEach((branch, index) => {
          if (index > 0) out.raw(' else ');
          if (branch.partial) {
            // Like an incomplete statement: for completion only.
            if (branch.test && this.assist) {
              out.raw('if (');
              out.copy(branch.test, false);
              out.raw(') ');
            }
            out.raw('{}');
            return;
          }
          if (branch.test) {
            out.raw('if (');
            out.copy(branch.test);
            out.raw(') ');
          }
          this.block(branch.body);
        });
        out.raw(' ');
        return;
      case 'for':
        out.raw('for (');
        out.copy(node.head);
        out.raw(') { ');
        if (node.key) {
          out.raw('__s.key(');
          out.copy(node.key);
          out.raw('); ');
        }
        for (const child of node.body) this.child(child);
        out.raw('} ');
        return;
      case 'switch':
        out.raw('switch (');
        out.copy(node.discriminant);
        out.raw(') { ');
        for (const c of node.cases) {
          if (c.test) {
            out.raw('case ');
            out.copy(c.test);
            out.raw(': ');
          } else out.raw('default: ');
          out.raw('{ ');
          for (const child of c.body) this.child(child);
          out.raw('break; } ');
        }
        out.raw('} ');
        return;
    }
  }

  block(body: ChildNode[]) {
    this.out.raw('{ ');
    for (const child of body) this.child(child);
    this.out.raw('}');
  }
}
